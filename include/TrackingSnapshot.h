#ifndef ORB_SLAM3_TRACKING_SNAPSHOT_H
#define ORB_SLAM3_TRACKING_SNAPSHOT_H

#include <cstdint>
#include <cstddef>
#include <type_traits>
#include <array>
#include <chrono>

namespace ORB_SLAM3
{

// Source time is independent of asynchronous log delivery order.
inline std::int64_t EvaluationSteadyNs() noexcept
{
    return std::chrono::duration_cast<std::chrono::nanoseconds>(
        std::chrono::steady_clock::now().time_since_epoch()).count();
}

enum class EvaluationEvent : std::size_t
{
    MapBaseline, TrackingLost, Relocalized, MapCreated, MapSwitched,
    ActiveMapReset, AtlasReset, MergeApplied, Count
};

inline constexpr std::array<const char*, static_cast<std::size_t>(EvaluationEvent::Count)>
    EvaluationEventNames{{"map_baseline", "tracking_lost", "relocalized", "map_created",
                          "map_switched", "active_map_reset", "atlas_reset", "merge_applied"}};

// Capture primitives under the caller's existing synchronization, never pointers.
struct EvaluationEventData
{
    std::int64_t steady_ns = 0;
    bool frame_valid = false;
    bool map_valid = false;
    bool target_map_valid = false;
    bool result_map_valid = false;
    bool keyframes_valid = false;
    std::uint64_t frame_id = 0;
    double sensor_timestamp_sec = 0.0;
    std::uint64_t map_id = 0;
    std::uint64_t target_map_id = 0;
    std::uint64_t result_map_id = 0;
    std::uint64_t keyframe_id = 0;
    std::uint64_t target_keyframe_id = 0;
};

struct EvaluationEventTotals
{
    bool enabled = false;
    std::array<std::uint64_t, EvaluationEventNames.size()> counts{};
};

// Numerical values from the last normally returned stereo tracking call. A
// throwing call does not replace System's published snapshot. No backend object
// is retained, so cached values remain readable after workers have joined.
struct TrackingSnapshot
{
    bool enabled = false;
    bool has_frame = false;
    bool map_id_valid = false;
    bool tracked_mappoint_inliers_valid = false;
    // Raw state at return, including a reset performed during this call.
    std::int32_t raw_tracking_state = 0; // NO_IMAGES_YET before the first frame.
    // Persistent, non-outlier feature associations counted by TrackLocalMap in
    // SLAM mode, before new KF points are added. This is not a unique-point count.
    // Initialization, skipped local tracking and localization-only mode are N/A.
    std::uint32_t tracked_mappoint_inliers = 0;
    // Entries/successes during this call, independent of the state at return.
    std::uint32_t tracking_lost_events = 0;
    std::uint32_t relocalization_events = 0;
    // Capture identity before Track can replace mCurrentFrame during map creation.
    std::uint64_t frame_id = 0;
    // Map used by this frame at the existing map-update synchronization point.
    // IDs may be rewritten by merge; this is not a coordinate-frame version.
    std::uint64_t tracking_map_id = 0;
    // Run-wide Atlas insertions sampled at return. Background insertion is
    // asynchronous; this does not count KFs generated by this particular frame.
    std::uint64_t keyframes_inserted_total = 0;
    double sensor_timestamp_sec = 0.0;

    // Separate setup-only opt-in, requiring enabled == true. Live Tcw maps
    // world points into the left camera frame; it is not an optimized history.
    bool pose_enabled = false;
    bool pose_valid = false;
    bool map_change_index_valid = false;
    bool imu_initialized_valid = false; // N/A for non-inertial stereo.
    bool imu_initialized = false;
    // Existing Map change counter, not a coordinate-frame/version guarantee.
    std::int32_t map_change_index = 0;
    // Source time of the map-locked capture, even if tracking has no valid pose.
    // Zero means that this call never reached a pose/context capture point.
    std::int64_t pose_capture_steady_ns = 0;
    // Read only when pose_valid. Translation is in metres; quaternion order is
    // explicitly x,y,z,w. Invalid zero-filled storage is not an identity pose.
    std::array<float, 3> pose_translation_cw{};
    std::array<float, 4> pose_quaternion_cw_xyzw{};
};

static_assert(std::is_trivially_copyable<TrackingSnapshot>::value &&
              std::is_standard_layout<TrackingSnapshot>::value,
              "Tracking snapshots must remain fixed-size numerical values");

} // namespace ORB_SLAM3

#endif
